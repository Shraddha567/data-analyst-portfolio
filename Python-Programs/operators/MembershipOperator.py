'''
Membership operators are special operator in python
in which we can test whether a value or variable
is found in a sequence (string, list, tuple, set and dictionary).
Two membership operators are:
1. in
2. not in
example:
x = "Hello World"
print("H" in x) # it will return True because H is present in x
print("h" in x) # it will return False because h is not present in x
print("Hello" not in x) # it will return False because Hello is present in x
print("hey" not in x) # it will return True because hey is not present in
x
'''