'''Ternary Operator is one line conditional Statement
It is a way to condense an if-else statement into a single line of code.
'''
age = 20
status = "Adult" if age >= 18 else "Minor"
print(status)  # Output: Adult
# In this example, the ternary operator checks if age is greater than or equal to 18. If true, it assigns "Adult" to status; otherwise, it assigns "Minor".